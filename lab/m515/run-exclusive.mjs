import {spawn} from 'node:child_process';
import {resolve, relative} from 'node:path';
import {acquireCampaign} from './campaign.mjs';
const root=process.env.PIDP551_WORK;
if(!root?.endsWith('/m515/v7')) throw Error('Explicit M5.15 V7 directory required');
const script=resolve(process.argv[2]??'');
if(!relative(resolve('lab'),script).endsWith('.mjs') || relative(resolve('lab'),script).startsWith('..')) throw Error('Reviewed local lab module required');
const release=acquireCampaign(root);
const child=spawn(process.execPath,[script],{stdio:'inherit',env:process.env});
for(const signal of ['SIGINT','SIGTERM']) process.on(signal,()=>child.kill(signal));
child.on('error',()=>{release();process.exitCode=1;});
child.on('exit',(code,signal)=>{release();process.exitCode=signal?1:code;});
